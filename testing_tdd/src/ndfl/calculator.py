"""
Расчёт НДФЛ по прогрессивной шкале РФ (с 2025 года).

Шкала ставок:
  До 2 400 000 руб.          — 13%
  2 400 000 – 5 000 000      — 15% (с суммы превышения)
  5 000 000 – 20 000 000     — 18% (с суммы превышения)
  20 000 000 – 50 000 000    — 20% (с суммы превышения)
  Свыше 50 000 000           — 22% (с суммы превышения)
"""

_BRACKETS = [
    (2_400_000,  0.13,         0),
    (5_000_000,  0.15,   312_000),
    (20_000_000, 0.18,   702_000),
    (50_000_000, 0.20, 3_402_000),
    (float("inf"), 0.22, 9_402_000),
]


def calculate_tax(income: float) -> float:
    if income < 0:
        raise ValueError(f"Negative income: {income}")

    brackets = [
        (50_000_000, 0.22, 9_402_000),
        (20_000_000, 0.20, 3_402_000),
        (5_000_000, 0.18, 702_000),
        (2_400_000, 0.15, 312_000),
        (0, 0.13, 0)
    ]

    for threshold, rate, base in brackets:
        if income > threshold:
            return base + (income - threshold) * rate

    return 0.0
